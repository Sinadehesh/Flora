#!/usr/bin/env node
// Downloads the curated plant photos listed in scripts/plant-photos.json from the
// iNaturalist Open Data bucket (AWS Open Data, no API key), resizes them for the
// app bundle, and regenerates src/data/plantImages.generated.ts with credits.
//
//   npm run photos:download             # fetch anything missing
//   npm run photos:download -- --force  # re-download and re-encode everything
//
// To add or swap photos, use `npm run photos:find -- <plant-id>` and edit
// scripts/plant-photos.json. Only CC0 / CC BY / CC BY-SA photos are allowed
// (no NC: the app may be sold).

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets/plants');
const listPath = join(root, 'scripts/plant-photos.json');
const generatedPath = join(root, 'src/data/plantImages.generated.ts');

const ALLOWED_LICENSES = new Set(['CC0', 'CC-BY', 'CC-BY-SA']);
const BUCKET = 'https://inaturalist-open-data.s3.amazonaws.com/photos';
const MAX_SIDE = 1000;

const force = process.argv.includes('--force');
const list = JSON.parse(readFileSync(listPath, 'utf8'));
mkdirSync(outDir, { recursive: true });

async function download(photoId, ext) {
  for (const size of ['large', 'medium']) {
    const res = await fetch(`${BUCKET}/${photoId}/${size}.${ext}`);
    if (res.ok) return Buffer.from(await res.arrayBuffer());
  }
  throw new Error(`photo ${photoId} not found in the open data bucket`);
}

const wanted = new Set();
let failures = 0;
for (const [plantId, photos] of Object.entries(list)) {
  for (const [i, photo] of photos.entries()) {
    const file = `${plantId}-${i + 1}.jpg`;
    wanted.add(file);
    if (!ALLOWED_LICENSES.has(photo.license)) {
      console.warn(`✗ ${file}: license ${photo.license} is not allowed`);
      failures++;
      continue;
    }
    if (!force && existsSync(join(outDir, file))) continue;
    try {
      const input = await download(photo.photoId, photo.ext);
      await sharp(input)
        .rotate()
        .resize(MAX_SIDE, MAX_SIDE, { fit: 'inside', withoutEnlargement: true })
        .jpeg({ quality: 74, mozjpeg: true })
        .toFile(join(outDir, file));
      console.log(`✓ ${file}`);
    } catch (err) {
      console.warn(`✗ ${file}: ${err.message}`);
      failures++;
    }
  }
}

// Drop photos that are no longer listed.
for (const file of readdirSync(outDir)) {
  if (file.endsWith('.jpg') && !wanted.has(file)) rmSync(join(outDir, file));
}

const licenseLabel = (code) => code.replace('CC-', 'CC ');
const lines = Object.entries(list)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([plantId, photos]) => {
    const items = photos
      .map((photo, i) => ({ photo, file: `${plantId}-${i + 1}.jpg` }))
      .filter(({ file }) => existsSync(join(outDir, file)))
      .map(({ photo, file }) => {
        const credit = JSON.stringify({
          author: photo.author,
          license: licenseLabel(photo.license),
          sourceUrl: photo.observationUrl,
        });
        return `    { source: require('../../assets/plants/${file}'), credit: ${credit} },`;
      });
    return items.length ? `  ${JSON.stringify(plantId)}: [\n${items.join('\n')}\n  ],` : null;
  })
  .filter(Boolean);

writeFileSync(
  generatedPath,
  `// Generated by scripts/download-plant-photos.mjs — do not edit by hand.
// Photos: iNaturalist observers, CC0 / CC BY / CC BY-SA. See scripts/plant-photos.json.
import type { PlantImage } from './plantImageTypes';

export const PLANT_IMAGES: Record<string, PlantImage[]> = {${lines.length ? `\n${lines.join('\n')}\n` : ''}};
`,
);
console.log(`\nWrote ${generatedPath} (${lines.length} plants).`);
if (failures) process.exitCode = 1;
